// ============================================================================
//  sCPU —— 支持 add / li / bner0 三条指令的简单处理器
//  指令集：sISA（ysyx F5 讲义）
//
//  指令格式（每条 8 位）：
//    add   : 7..6=00 | 5..4=rd | 3..2=rs1 | 1..0=rs2    R[rd] = R[rs1] + R[rs2]
//    li    : 7..6=10 | 5..4=rd | 3..0=imm               R[rd] = imm
//    bner0 : 7..6=11 | 5..2=addr | 1..0=rs2             if (R[0] != R[rs2]) PC = addr
//
//  规格：PC 8 位；GPR 4 个 × 8 位；指令存储器 256 × 8
// ============================================================================
module scpu (
    input        clk,
    input        rst,           // 同步复位，高有效
    output [7:0] pc_out,
    output [7:0] r0_out,
    output [7:0] r1_out,
    output [7:0] r2_out,
    output [7:0] r3_out
);

    // ------------------------------------------------------------------
    // 1. PC（程序计数器）
    // ------------------------------------------------------------------
    reg [7:0] pc;

    // ------------------------------------------------------------------
    // 2. 指令存储器（ROM 256 × 8）
    // ------------------------------------------------------------------
    reg [7:0] rom [0:255];
    wire [7:0] instr = rom[pc];              // 取指

    // ------------------------------------------------------------------
    // 3. 指令译码（对应 Logisim 里的 Splitter）
    // ------------------------------------------------------------------
    wire [1:0] opcode = instr[7:6];
    wire [1:0] rd     = instr[5:4];
    wire [1:0] rs1    = instr[3:2];
    wire [1:0] rs2    = instr[1:0];
    wire [3:0] imm    = instr[3:0];          // li 的立即数
    wire [3:0] addr   = instr[5:2];          // bner0 的跳转地址

    // 指令类型判断（对应 NOT + AND 算出的 li_en / add_en）
    wire is_add   = (opcode == 2'b00);
    wire is_li    = (opcode == 2'b10);
    wire is_bner0 = (opcode == 2'b11);

    // ------------------------------------------------------------------
    // 4. GPR（4 × 8 位，双读口）
    //    对应：4 个 Register + 两个 mux41（双读口）
    // ------------------------------------------------------------------
    reg [7:0] gpr [0:3];

    wire [7:0] rdata1 = gpr[rs1];            // 读口 1
    wire [7:0] rdata2 = gpr[rs2];            // 读口 2

    // ------------------------------------------------------------------
    // 5. ALU（8 位加法器）
    // ------------------------------------------------------------------
    wire [7:0] add_result = rdata1 + rdata2;

    // ------------------------------------------------------------------
    // 6. 写回数据选择（对应 mux41#3）
    //    li  -> 零扩展的立即数
    //    其他 -> 加法结果
    // ------------------------------------------------------------------
    wire [7:0] wdata = is_li ? {4'b0, imm} : add_result;

    // ------------------------------------------------------------------
    // 7. GPR 写使能（对应 OR 门 + 4 个与门）
    //    只有 li / add 会写 GPR；bner0 只改 PC
    // ------------------------------------------------------------------
    wire wen = is_li | is_add;

    // ------------------------------------------------------------------
    // 8. bner0 的跳转判断（对应比较器）
    // ------------------------------------------------------------------
    wire bne      = (gpr[0] != rdata2);      // R[0] != R[rs2] ?
    wire pc_taken = is_bner0 & bne;

    // ------------------------------------------------------------------
    // 9. PC 的下一个值（对应 PC 输入 MUX）
    // ------------------------------------------------------------------
    wire [7:0] pc_next = pc_taken ? {4'b0, addr} : (pc + 8'd1);

    // ------------------------------------------------------------------
    // 10. 程序装载：计算 1 + 2 + ... + 10
    // ------------------------------------------------------------------
    integer i;
    initial begin
        rom[0] = 8'h8A;      // li r0, 10      1000 1010
        rom[1] = 8'h90;      // li r1, 0       1001 0000
        rom[2] = 8'hA0;      // li r2, 0       1010 0000
        rom[3] = 8'hB1;      // li r3, 1       1011 0001
        rom[4] = 8'h17;      // add r1, r1, r3 0001 0111
        rom[5] = 8'h29;      // add r2, r2, r1 0010 1001
        rom[6] = 8'hD1;      // bner0 r1, 4    1101 0001
        rom[7] = 8'hDF;      // bner0 r3, 7    1101 1111
        for (i = 8; i < 256; i = i + 1)
            rom[i] = 8'h00;  // 其余为 0

        pc = 8'd0;
        for (i = 0; i < 4; i = i + 1)
            gpr[i] = 8'd0;
    end

    // ------------------------------------------------------------------
    // 11. 时序逻辑（对应 Clock + 触发器）
    //     注意用非阻塞赋值 <= ：保证"所有寄存器同一时刻更新"
    // ------------------------------------------------------------------
    always @(posedge clk) begin
        if (rst) begin
            pc <= 8'd0;
            for (i = 0; i < 4; i = i + 1)
                gpr[i] <= 8'd0;
        end
        else begin
            if (wen)
                gpr[rd] <= wdata;     // 写 GPR
            pc <= pc_next;            // 更新 PC
        end
    end

    // ------------------------------------------------------------------
    // 观察口
    // ------------------------------------------------------------------
    assign pc_out = pc;
    assign r0_out = gpr[0];
    assign r1_out = gpr[1];
    assign r2_out = gpr[2];
    assign r3_out = gpr[3];

endmodule
